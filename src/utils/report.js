import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

export function generatePdfReport(result, fullText = '') {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 20;

  // Header bar
  doc.setFillColor(11, 31, 58); // Deep navy
  doc.rect(0, 0, pageWidth, 28, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('DetectAI — Analysis Report', 14, 18);

  y = 40;
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');

  const rows = [
    ['Document', result.fileName || 'Pasted text'],
    ['Date', new Date(result.createdAt).toLocaleString()],
    ['Word Count', String(result.wordCount || 0)],
    ['AI Probability', `${result.aiScore}%`],
    ['Human Probability', `${result.humanScore}%`],
    ['Classification', result.aiScore >= 65 ? 'Likely AI-generated' : result.humanScore >= 65 ? 'Likely Human-written' : 'Mixed / Uncertain'],
    ['Detection Source', result.source === 'ai_model' ? 'AI Model + Heuristic' : 'Heuristic only'],
  ];

  autoTable(doc, {
    startY: y,
    head: [['Field', 'Value']],
    body: rows,
    theme: 'striped',
    headStyles: { fillColor: [37, 99, 235] },
    styles: { fontSize: 10 },
    margin: { left: 14, right: 14 },
  });

  y = doc.lastAutoTable.finalY + 12;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Summary', 14, y);
  y += 7;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const summaryLines = doc.splitTextToSize(result.summary || 'No summary available.', pageWidth - 28);
  doc.text(summaryLines, 14, y);
  y += summaryLines.length * 5 + 8;

  if (result.modelReasoning) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.text('Model Reasoning', 14, y);
    y += 7;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    const reasonLines = doc.splitTextToSize(result.modelReasoning, pageWidth - 28);
    doc.text(reasonLines, 14, y);
    y += reasonLines.length * 5 + 8;
  }

  // Disclaimer
  if (y > 250) {
    doc.addPage();
    y = 20;
  }
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  const disclaimer =
    'Disclaimer: AI text detection is probabilistic and cannot reliably establish authorship. ' +
    'Results are analytical signals only and should not be treated as definitive proof. ' +
    'Short, edited, translated, or mixed-origin texts may produce false positives or false negatives.';
  const discLines = doc.splitTextToSize(disclaimer, pageWidth - 28);
  doc.text(discLines, 14, y);

  // Footer
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${pageCount} · Generated by DetectAI`, pageWidth / 2, 290, { align: 'center' });
  }

  doc.save(`detectai-report-${result._id || Date.now()}.pdf`);
}

export function exportJson(result) {
  const blob = new Blob([JSON.stringify(result, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `detectai-${result._id || 'export'}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportTxt(result) {
  const content = `DetectAI Analysis Report
========================
Document: ${result.fileName}
Date: ${new Date(result.createdAt).toLocaleString()}
AI Probability: ${result.aiScore}%
Human Probability: ${result.humanScore}%
Word Count: ${result.wordCount}
Source: ${result.source}
Summary: ${result.summary}
${result.modelReasoning ? `Reasoning: ${result.modelReasoning}` : ''}

Disclaimer: Detection is probabilistic and not proof of authorship.
`;
  const blob = new Blob([content], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `detectai-${result._id || 'export'}.txt`;
  a.click();
  URL.revokeObjectURL(url);
}
